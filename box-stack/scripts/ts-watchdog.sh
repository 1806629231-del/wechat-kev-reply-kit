#!/usr/bin/env bash
#
# ts-watchdog.sh — keep the box Tailscale daemon and the phone SOCKS path
# healthy for a box-hosted WeChat.
#
# Restart policy (conservative):
#   A. phone AutoX unreachable AND no Tailscale interface -> restart tailscaled
#   B. Tailscale local API dead (even if the process/interface look alive)
#      -> restart tailscaled
#   C. phone + API healthy but SOCKS egress is dead -> log a warning only
#
# Never restarts more often than MIN_GAP seconds (default 600).
#
# Configurable environment (or $TS_WATCHDOG_ENV):
#   PHONE_TS_IP        Tailscale IP of the phone/exit device
#   BOX_TS_IP_PREFIX   Prefix of the box Tailscale IP (default: 100.)
#   SOCKS_ENV          Secrets file (default: $HOME/secrets/phone-socks.env)
#   TS_STATE_DIR       Tailscale state directory (default: $HOME/tailscale)
#   MIN_GAP            Minimum seconds between restarts (default: 600)
#   TS_SOCKET          tailscaled socket (default: /run/tailscale/tailscaled.sock)
#
# Usage: ts-watchdog.sh [--once]
#
# This script never prints credentials.

set -uo pipefail

# Load optional generated config first so TS_STATE_DIR/TS_SOCKET from it are
# reflected in the derived paths below.
ENV_FILE="${TS_WATCHDOG_ENV:-$HOME/.config/wechat-box/watchdog.env}"
if [[ -r "$ENV_FILE" ]]; then
  # Generated by install.sh (mode 600). Values are simple shell assignments.
  # shellcheck disable=SC1090
  . "$ENV_FILE"
fi

SOCK="${TS_SOCKET:-/run/tailscale/tailscaled.sock}"
TS_STATE_DIR="${TS_STATE_DIR:-$HOME/tailscale}"
STATE="$TS_STATE_DIR/tailscaled.state"
LOG="${TS_WATCHDOG_LOG:-/tmp/ts-watchdog.log}"
LAST_RESTART_FILE="${TS_WATCHDOG_STAMP:-/tmp/ts-watchdog.last_restart}"
SOCKS_ENV="${SOCKS_ENV:-$HOME/secrets/phone-socks.env}"
BOX_TS_IP_PREFIX="${BOX_TS_IP_PREFIX:-100.}"
MIN_GAP="${MIN_GAP:-600}"
PHONE_TS_IP="${PHONE_TS_IP:-}"

[[ "$MIN_GAP" =~ ^[0-9]+$ ]] || MIN_GAP=600
[[ "$BOX_TS_IP_PREFIX" == *.* ]] || BOX_TS_IP_PREFIX="${BOX_TS_IP_PREFIX}."

ONCE=0
[[ "${1:-}" == "--once" ]] && ONCE=1

log() {
  printf '%s %s\n' "$(date '+%F %T')" "$*" >>"$LOG"
}

ts_bin() {
  if command -v tailscaled >/dev/null 2>&1; then
    command -v tailscaled
  elif [[ -x /usr/sbin/tailscaled ]]; then
    echo /usr/sbin/tailscaled
  else
    return 1
  fi
}

# Parse the secrets file without executing it. Prefer PHONE_SOCKS_* names,
# fall back to legacy SOCKS_* names.
load_socks() {
  PHONE_SOCKS_HOST=""
  PHONE_SOCKS_PORT=""
  PHONE_SOCKS_USER=""
  PHONE_SOCKS_PASS=""

  [[ -f "$SOCKS_ENV" ]] || return 1

  local line key val
  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line%%$'\r'}"
    [[ -z "$line" || "$line" == \#* ]] && continue
    [[ "$line" == export\ * ]] && line="${line#export }"
    key="${line%%=*}"
    val="${line#*=}"
    key="${key//[[:space:]]/}"
    val="${val#\"}"; val="${val%\"}"
    val="${val#\'}"; val="${val%\'}"
    case "$key" in
      PHONE_SOCKS_HOST) PHONE_SOCKS_HOST="$val" ;;
      PHONE_SOCKS_PORT) PHONE_SOCKS_PORT="$val" ;;
      PHONE_SOCKS_USER) PHONE_SOCKS_USER="$val" ;;
      PHONE_SOCKS_PASS) PHONE_SOCKS_PASS="$val" ;;
      SOCKS_HOST) [[ -z "$PHONE_SOCKS_HOST" ]] && PHONE_SOCKS_HOST="$val" ;;
      SOCKS_PORT) [[ -z "$PHONE_SOCKS_PORT" ]] && PHONE_SOCKS_PORT="$val" ;;
      SOCKS_USER) [[ -z "$PHONE_SOCKS_USER" ]] && PHONE_SOCKS_USER="$val" ;;
      SOCKS_PASS) [[ -z "$PHONE_SOCKS_PASS" ]] && PHONE_SOCKS_PASS="$val" ;;
    esac
  done <"$SOCKS_ENV"

  PHONE_SOCKS_PORT="${PHONE_SOCKS_PORT:-1080}"
  [[ -n "$PHONE_SOCKS_HOST" && "$PHONE_SOCKS_HOST" != *"<"* ]] || return 1
  [[ -n "$PHONE_SOCKS_USER" && "$PHONE_SOCKS_USER" != *"<"* ]] || return 1
  [[ -n "$PHONE_SOCKS_PASS" && "$PHONE_SOCKS_PASS" != *"<"* ]] || return 1
  [[ "$PHONE_SOCKS_PORT" =~ ^[0-9]+$ ]] || return 1
  return 0
}

# The phone IP can come from the environment or from the secrets file.
phone_configured() {
  if [[ -n "$PHONE_TS_IP" ]]; then
    return 0
  fi
  if load_socks; then
    PHONE_TS_IP="$PHONE_SOCKS_HOST"
    return 0
  fi
  return 1
}

phone_ok() {
  [[ -n "$PHONE_TS_IP" ]] || return 1
  curl -s -m 8 "http://${PHONE_TS_IP}:8765/status" 2>/dev/null | grep -q '"v"' && return 0
  curl -s -m 8 "http://${PHONE_TS_IP}:8766/status" 2>/dev/null | grep -q '"v"'
}

ts_api_ok() {
  [[ -S "$SOCK" ]] || return 1
  command -v tailscale >/dev/null 2>&1 || return 1
  local out
  out="$(timeout 10 tailscale --socket="$SOCK" status 2>&1 || true)"
  [[ -n "$out" ]] || return 1
  # "Logged out" still proves the local API answered. Only these errors mean
  # the socket/daemon is actually unreachable.
  ! printf '%s' "$out" | grep -qiE 'failed to connect|connection refused|no such file|timed out'
}

ts_iface_ok() {
  ip -4 addr show dev tailscale0 2>/dev/null | grep -qF "inet ${BOX_TS_IP_PREFIX}"
}

socks_ok() {
  load_socks || return 1

  # Credentials go through curl's stdin config (-K -), never argv.
  local out
  out="$(curl -sS -L -m 15 -K - <<EOF 2>/dev/null
socks5-hostname = "${PHONE_SOCKS_HOST}:${PHONE_SOCKS_PORT}"
proxy-user = "${PHONE_SOCKS_USER}:${PHONE_SOCKS_PASS}"
url = "https://myip.ipip.net"
EOF
)"
  printf '%s' "$out" | grep -q '中国' && return 0

  out="$(curl -sS -L -m 15 -K - <<EOF 2>/dev/null
socks5-hostname = "${PHONE_SOCKS_HOST}:${PHONE_SOCKS_PORT}"
proxy-user = "${PHONE_SOCKS_USER}:${PHONE_SOCKS_PASS}"
url = "https://ipinfo.io/country"
EOF
)"
  [[ "$(printf '%s' "$out" | tr -d '[:space:]')" == "CN" ]]
}

can_restart() {
  local now last
  now="$(date +%s)"
  last="$(cat "$LAST_RESTART_FILE" 2>/dev/null || echo 0)"
  [[ "$last" =~ ^[0-9]+$ ]] || last=0
  (( now - last >= MIN_GAP ))
}

ensure_socket_links() {
  sudo -n mkdir -p /run/tailscale /var/run/tailscale 2>/dev/null || true
  sudo -n ln -sfn "$SOCK" /var/run/tailscale/tailscaled.sock 2>/dev/null || true
}

do_restart() {
  local reason="$1" bin
  if ! sudo -n true 2>/dev/null; then
    log "restart skipped ($reason): no passwordless sudo"
    return 1
  fi
  if ! bin="$(ts_bin)"; then
    log "restart skipped ($reason): tailscaled binary not found"
    return 1
  fi

  log "restart: $reason"
  date +%s >"$LAST_RESTART_FILE"

  sudo -n pkill -x tailscaled 2>/dev/null || true
  sleep 2
  sudo -n mkdir -p /run/tailscale /var/run/tailscale 2>/dev/null || true
  sudo -n ln -sfn "$SOCK" /var/run/tailscale/tailscaled.sock 2>/dev/null || true
  mkdir -p "$TS_STATE_DIR" 2>/dev/null || true

  sudo -n nohup "$bin" --state="$STATE" --socket="$SOCK" \
    --statedir="$TS_STATE_DIR" >>/tmp/tsd.log 2>&1 &
  sleep 15

  log "after: api=$(ts_api_ok && echo ok || echo bad) phone=$(phone_ok && echo ok || echo bad) socks=$(socks_ok && echo ok || echo bad)"
}

ensure_socket_links

if ! phone_configured; then
  log "warn: PHONE_TS_IP not configured; phone-based restart decision disabled"
fi

while true; do
  p_ok=0; a_ok=0; i_ok=0; s_ok=0
  phone_ok && p_ok=1
  ts_api_ok && a_ok=1
  ts_iface_ok && i_ok=1

  # The SOCKS probe is slower; only run it when something already looks wrong.
  if [[ "$p_ok" -eq 0 || "$a_ok" -eq 0 ]]; then
    socks_ok && s_ok=1 || s_ok=0
  else
    s_ok=1
  fi

  if [[ "$p_ok" -eq 0 && "$i_ok" -eq 0 ]]; then
    # Case A: phone gone and the box has no Tailscale address.
    if can_restart; then
      do_restart "phone_down+no_iface" || true
    fi
  elif [[ "$a_ok" -eq 0 ]]; then
    # Case B: daemon or local API unhealthy. This was the real failure mode:
    # the process stayed alive but its API socket stopped answering.
    if can_restart; then
      do_restart "tailscale_api_dead" || true
    fi
  elif [[ "$p_ok" -eq 1 && "$a_ok" -eq 1 && "$s_ok" -eq 0 ]]; then
    # Case C: the phone and Tailscale are up; the SOCKS app needs attention.
    log "warn: socks_egress_dead (phone AutoX up; check the SOCKS app)"
  fi

  [[ "$ONCE" -eq 1 ]] && break
  sleep 60
done
